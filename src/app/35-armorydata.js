// —— 轮盘纯数学（71-armory 用，tools/tests_pure/test_armory.py 测）——
// rot：轮盘转到的位置，单位“条目”（0 = 第 0 条对准指针，可为小数）
// 条目 i 相对指针的角度（弧度）= (i - rot) × 每格角度，并把环绕差值规整到 [-n/2, n/2)
function armoryStep(n) { return Math.PI * 2 / n; }
function armoryRel(i, rot, n) {
  let d = ((i - rot) % n + n) % n;
  if (d >= n / 2) d -= n;
  return d;
}
function armoryNearest(rot, n) { return ((Math.round(rot) % n) + n) % n; }
// 从当前 rot 走到条目 i 的最短目标 rot（不跳圈，避免 13→0 时反向转一整圈）
function armoryTarget(i, rot, n) { return rot + armoryRel(i, rot, n); }
